/**
 * web-kit is this checkout; a sibling counts as present only if its directory exists - under
 * whatever case the clone arrived in, which on a runner is GitHub's spelling and not this
 * workspace's. See scripts/siblings.mjs.
 */
const present = (owner) => owner === "web-kit" || existsSync(sibling(repo, owner));

let drift = 0;
const skipped = new Set();
for (const [owner, path, body] of artifacts) {
  if (!present(owner)) {
    skipped.add(owner);
    continue;
  }
  if (checkOnly) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (current !== body) {
      console.error(`drift: ${path.replace(repo, ".")} does not match tokens.json`);
      drift++;
    }
    continue;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, body, "utf8");
  console.log(`wrote ${path.replace(repo, ".")}`);
}
if (skipped.size) {
  console.log(`\nskipped (repository not checked out here): ${[...skipped].sort().join(", ")}`);
}

