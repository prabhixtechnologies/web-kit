// The tag tone list and the seed-to-swatch rule, emitted for TypeScript as well as Dart.
// Both sides have to agree or the same sender is one colour in the browser and another in
// the app, so neither side gets to keep its own copy of the order.
function buildTagsTs() {
  const L = [BANNER("tags.ts").trimEnd(), ""];
  L.push("/** The generated tag tones, in palette order. Index 0 is the neutral 'no category' swatch. */");
  L.push("export const TAG_TONES = [");
  for (const n of T.palette.tag.ramps) L.push(`  "${n}",`);
  L.push("] as const;");
  L.push("");
  L.push("export type TagTone = (typeof TAG_TONES)[number];");
  L.push("");
  L.push("/**");
  L.push(" * Picks a stable swatch for a piece of text: a sender, a label, a tenant. The same");
  L.push(" * name is always the same colour, without storing a colour per record.");
  L.push(" *");
  L.push(" * Must stay identical to `pxTagFor` in prabhix_tokens.dart.");
  L.push(" */");
  L.push("export function toneFor(seed: string): TagTone {");
  L.push("  let hash = 0;");
  L.push("  for (let i = 0; i < seed.length; i += 1) {");
  L.push("    hash = (hash * 31 + seed.charCodeAt(i)) & 0x1fffffff;");
  L.push("  }");
  L.push("  // Skips index 0, the neutral swatch, which is reserved for 'no category'.");
  L.push("  return TAG_TONES[1 + (hash % (TAG_TONES.length - 1))];");
  L.push("}");
  L.push("");
  L.push("/**");
  L.push(" * The resolved hex for each swatch, for the few places that cannot use a CSS variable.");
  L.push(" *");
  L.push(" * Prefer `var(--px-tag-<tone>-bg)` and `-ink` everywhere you can: those follow the mode,");
  L.push(" * and these do not. This exists for values that leave the stylesheet — a colour written to");
  L.push(" * the database, an `<input type=\"color\">`, a third-party SDK that takes a hex string. Both");
  L.push(" * modes are given so a caller storing one can also show the other correctly.");
  L.push(" *");
  L.push(" * Every ink is asserted AA against its own bg by the contrast gate. Nothing is asserted");
  L.push(" * about an ink on any other background, so do not pair them across tones.");
  L.push(" */");
  L.push("export const TAG_SWATCHES: Record<");
  L.push("  \"light\" | \"dark\",");
  L.push("  Record<TagTone, { bg: string; ink: string; border: string }>");
  L.push("> = {");
  for (const mode of ["light", "dark"]) {
    L.push(`  ${mode}: {`);
    for (const t of tagSwatches()[mode]) {
      L.push(`    ${t.name}: { bg: "${t.bg}", ink: "${t.ink}", border: "${t.border}" },`);
    }
    L.push("  },");
  }
  L.push("};");
  L.push("");
  return L.join("\n");
}

/* ---------- helpers ---------- */

function kebab(s) { return s.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase()); }
function camel(s) { return s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()); }
function pascal(s) { const c = camel(s); return c[0].toUpperCase() + c.slice(1); }
function round(n) { return Math.round(n * 100) / 100; }

