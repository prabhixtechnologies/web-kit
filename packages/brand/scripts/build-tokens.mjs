#!/usr/bin/env node
// Generates every design-token artifact in the portfolio from tokens.json.
// Fails the build when a required contrast pair regresses, so a colour change
// cannot quietly drop a surface below WCAG AA.
//
//   node scripts/build-tokens.mjs           build
//   node scripts/build-tokens.mjs --check   verify the checked-in output matches

